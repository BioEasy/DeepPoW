# Function: Provide BEAST 2 XML hot-patching and RMSD Python script generation utilities (CIF/AlphaFold3 supported)

library(xml2)

#' Automatically patch BEAST 2 XML (inject branchRates logger)
#'
#' Parses the uploaded BEAST2 XML file, locates the Relaxed Clock model,
#' and injects it into the TreeLogger (<logger id="treelog...") to ensure branch rates are logged.
#' 
#' @param xml_path Path to the original XML file
#' @return list(success = Boolean, doc = xml_document, msg = String)
patch_beast2_xml <- function(xml_path) {
  
  doc <- xml2::read_xml(xml_path)
  brm_nodes <- xml2::xml_find_all(doc, "//*[@spec='beast.evolution.branchratemodel.UCRelaxedClockModel' or contains(@spec, 'RelaxedClock') or contains(@id, 'RelaxedClock')]")
  
  if (length(brm_nodes) == 0) {
    return(list(
      success = FALSE, 
      doc = NULL, 
      msg = "[FAIL] Could not find Relaxed Clock model in the XML.\nPlease ensure you selected a Relaxed Clock model instead of a Strict Clock in BEAUti."
    ))
  }

  brm_id <- xml2::xml_attr(brm_nodes[[1]], "id")
  if (is.na(brm_id) || brm_id == "") {
    return(list(success = FALSE, doc = NULL, msg = "[FAIL] Clock model found, but failed to parse its 'id' attribute."))
  }
  
  tree_loggers <- xml2::xml_find_all(doc, "//logger[contains(@id, 'treelog') or contains(@fileName, '.trees')]")
  
  if (length(tree_loggers) == 0) {
    return(list(success = FALSE, doc = NULL, msg = "[FAIL] Could not find the <logger> node for .trees output."))
  }
  
  tree_logger_node <- tree_loggers[[1]]
  
  existing_logs <- xml2::xml_find_all(tree_logger_node, paste0("./log[@idref='", brm_id, "']"))
  if (length(existing_logs) > 0) {
    return(list(
      success = TRUE, 
      doc = doc, 
      msg = paste0("[SUCCESS] Your XML already contains the required logger: <log idref=\"", brm_id, "\"/>\nNo changes needed. Your .trees file should already include branch rates.")
    ))
  }
  
  new_log_element <- xml2::read_xml(paste0("<log idref=\"", brm_id, "\"/>"))
  xml2::xml_add_child(tree_logger_node, new_log_element)
  
  success_msg <- paste0(
    "[SUCCESS] Patch injected successfully!\n",
    "-> Detected Relaxed Clock ID: ", brm_id, "\n",
    "-> Injected into Tree Logger: ", xml2::xml_attr(tree_logger_node, "id"), "\n\n",
    "You can now download the Patched XML to resume your MCMC run."
  )
  
  return(list(success = TRUE, doc = doc, msg = success_msg))
}


#' Generate robust Python scaffold script for calculating structural distance matrices (CIF/AlphaFold3 compatible)
#'
#' @param engine String, "Foldseek" or "TM-align"
#' @param pdb_dir String, path to AlphaFold3 CIF directory
#' @param output_csv String, filename for the output distance matrix CSV
#' @return String containing the Python script text
generate_rmsd_script <- function(engine, pdb_dir, output_csv) {
  
  if (grepl("Foldseek", engine, ignore.case = TRUE)) {
    py_code <- paste0(
      "#!/usr/bin/env python3\n",
      "# Auto-generated by DeepPoW Utilities (AlphaFold3 CIF-supported)\n",
      "# This script calculates all-vs-all structural alignments using Foldseek easy-search and saves a distance matrix CSV.\n\n",
      "import os\n",
      "import glob\n",
      "import subprocess\n",
      "import pandas as pd\n",
      "import numpy as np\n",
      "import shutil\n\n",
      "PDB_DIR = '", pdb_dir, "'\n",
      "OUTPUT_CSV = '", output_csv, "'\n\n",
      "def main():\n",
      "    # Search for all CIF structures (AlphaFold3 output standard)\n",
      "    pdb_files = sorted(glob.glob(os.path.join(PDB_DIR, '*.cif')))\n",
      "    if not pdb_files:\n",
      "        print(f'[Error] No CIF files found in {PDB_DIR}')\n",
      "        return\n\n",
      "    taxa = [os.path.splitext(os.path.basename(f))[0] for f in pdb_files]\n",
      "    n = len(taxa)\n",
      "    print(f'Found {n} structures. Running all-vs-all structural alignment via Foldseek easy-search...')\n\n",
      "    aln_file = 'aln.m8'\n",
      "    tmp_dir = 'tmp_fs'\n\n",
      "    # Cleanup old temp alignment file if exists\n",
      "    if os.path.exists(aln_file):\n",
      "        os.remove(aln_file)\n\n",
      "    # Execute Foldseek easy-search\n",
      "    cmd = [\n",
      "        'foldseek', 'easy-search',\n",
      "        PDB_DIR, PDB_DIR,\n",
      "        aln_file, tmp_dir,\n",
      "        '--format-output', 'query,target,fident,alnlen,mismatch,gapopen,qstart,qend,tstart,tend,evalue,bits',\n",
      "        '-a'\n",
      "    ]\n\n",
      "    print('Executing:', ' '.join(cmd))\n",
      "    subprocess.run(cmd, check=True)\n\n",
      "    # Parse m8 alignment output\n",
      "    print('Alignment complete. Parsing m8 output to CSV matrix...')\n",
      "    col_names = ['query', 'target', 'fident', 'alnlen', 'mismatch', 'gapopen', \n",
      "                 'qstart', 'qend', 'tstart', 'tend', 'evalue', 'bits']\n\n",
      "    # Initialize square matrix with default distance 1.0\n",
      "    matrix = pd.DataFrame(1.0, index=taxa, columns=taxa)\n",
      "    for t in taxa:\n",
      "        matrix.loc[t, t] = 0.0\n\n",
      "    if os.path.exists(aln_file) and os.path.getsize(aln_file) > 0:\n",
      "        df_aln = pd.read_csv(aln_file, sep='\\t', names=col_names)\n",
      "        \n",
      "        # Clean query and target names to match Taxon IDs\n",
      "        df_aln['query'] = df_aln['query'].astype(str).apply(lambda x: os.path.splitext(os.path.basename(x))[0])\n",
      "        df_aln['target'] = df_aln['target'].astype(str).apply(lambda x: os.path.splitext(os.path.basename(x))[0])\n\n",
      "        print(f'Loaded {len(df_aln)} alignment hits from aln.m8')\n\n",
      "        max_bits = df_aln['bits'].max() if not df_aln['bits'].empty else 1.0\n",
      "        if max_bits == 0:\n",
      "            max_bits = 1.0\n\n",
      "        for _, row in df_aln.iterrows():\n",
      "            q = row['query']\n",
      "            t = row['target']\n",
      "            if q in taxa and t in taxa:\n",
      "                dist = 1.0 - (row['bits'] / max_bits)\n",
      "                dist = max(0.0, min(1.0, dist))\n",
      "                matrix.loc[q, t] = dist\n",
      "                matrix.loc[t, q] = dist\n",
      "    else:\n",
      "        print('[Warning] aln.m8 is empty or not found!')\n\n",
      "    # Ensure strict zero diagonal\n",
      "    for t in taxa:\n",
      "        matrix.loc[t, t] = 0.0\n\n",
      "    # Save final matrix to CSV\n",
      "    matrix.to_csv(OUTPUT_CSV)\n",
      "    print(f'Successfully saved matrix to {OUTPUT_CSV}')\n\n",
      "    # Cleanup temporary files\n",
      "    if os.path.exists(tmp_dir):\n",
      "        shutil.rmtree(tmp_dir, ignore_errors=True)\n",
      "    if os.path.exists(aln_file):\n",
      "        os.remove(aln_file)\n\n",
      "if __name__ == '__main__':\n",
      "    main()\n"
    )
    return(py_code)
  } else {
    py_code <- paste0(
      "#!/usr/bin/env python3\n",
      "# Auto-generated by DeepPoW Utilities (TM-align)\n\n",
      "import os\n",
      "import glob\n",
      "import numpy as np\n",
      "import pandas as pd\n\n",
      "PDB_DIR = '", pdb_dir, "'\n",
      "OUTPUT_CSV = '", output_csv, "'\n\n",
      "def main():\n",
      "    cif_files = sorted(glob.glob(os.path.join(PDB_DIR, '*.cif')))\n",
      "    if not cif_files:\n",
      "        print(f'No CIF files found in {PDB_DIR}')\n",
      "        return\n",
      "    print('TM-align implementation placeholder...')\n\n",
      "if __name__ == '__main__':\n",
      "    main()\n"
    )
    return(py_code)
  }
}